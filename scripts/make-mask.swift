import AppKit
let img = NSImage(contentsOfFile: "/System/Library/PrivateFrameworks/GeoKit.framework/Versions/A/Resources/worldmap.png")!
let rep = NSBitmapImageRep(data: img.tiffRepresentation!)!
let W = rep.pixelsWide, H = rep.pixelsHigh
let cols = 116, rows = 58
var out = "// Generated by scripts/make-mask.swift from the GeoKit world map — 116×58 equirectangular land mask, \"#\" = land.\nenum WorldMask {\n    static let cols = \(cols), rows = \(rows)\n    static let land: [String] = [\n"
for r in 0..<rows {
  var line = ""
  for c in 0..<cols {
    var land = 0, total = 0
    let x0 = c*W/cols, x1 = (c+1)*W/cols, y0 = r*H/rows, y1 = (r+1)*H/rows
    for y in y0..<y1 { for x in x0..<x1 {
      let col = rep.colorAt(x: x, y: y)!
      total += 1
      if col.alphaComponent > 0.5 && col.brightnessComponent < 0.5 { land += 1 }
    }}
    line += Double(land)/Double(total) > 0.35 ? "#" : "."
  }
  out += "        \"\(line)\",\n"
}
out += "    ]\n}\n"
print(out, terminator: "")
